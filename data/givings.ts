export async function fetchPaginatedGivings(
  pageIndex: number,
  pageSize: number
): Promise<PaginatedResponse<Giving>> {
  await new Promise((resolve) => setTimeout(resolve, 300));

  const startIndex = pageIndex * pageSize;
  const endIndex = startIndex + pageSize;

  const paginatedData = givings.slice(startIndex, endIndex);

  return {
    data: paginatedData,
    totalItems: givings.length,
    pageCount: Math.ceil(givings.length / pageSize),
  };
}

export function getGiving(id: string): Giving | undefined {
  return givings.find((giving) => giving.id === id);
}
